def generate_pronunciable_password(length=15) -> str:
    _letter = random.choice(ALFABET)
    buff = [_letter]
    num_letters = max(6, length - 5)
    for _ in range(num_letters - 1):
        population, weights = FREQUENCIES[_letter]
        _letter = random.choices(population, cum_weights=weights)[0]
        buff.append(_letter)
    word = "".join(buff).capitalize()
    symbol = random.choice(SYMBOLS)
    year = Date.today().year % 100
    num = f'{random.choice(DIGITS)}{random.choice(DIGITS)}'
    return f"{word}{symbol}{num}{year}"


